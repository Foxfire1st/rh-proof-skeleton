"""Deterministic provenance-preserving Lean skeleton stub emitter."""

from __future__ import annotations

from rh_pipeline.models.dag import DagDeclarationRef
from rh_pipeline.models.lean import ExtractedModule, LeanDeclaration, LeanDeclarationKind

_ALWAYS_VERBATIM_KINDS: frozenset[LeanDeclarationKind] = frozenset(
    {"structure", "inductive", "class", "opaque", "axiom"}
)
_DEF_KINDS: frozenset[LeanDeclarationKind] = frozenset({"def", "abbrev"})


def _should_emit_verbatim(kind: LeanDeclarationKind, *, preserve_defs: bool) -> bool:
    if kind in _ALWAYS_VERBATIM_KINDS:
        return True
    return preserve_defs and kind in _DEF_KINDS


def _format_verbatim_declaration(decl: LeanDeclaration) -> str:
    if decl.body == "":
        return decl.signature
    if decl.body.startswith((" ", "\t")):
        return f"{decl.signature} :=\n{decl.body}"
    return f"{decl.signature} := {decl.body}"


def _emit_verbatim_block(
    decl: LeanDeclaration,
    *,
    start_line: int,
) -> tuple[list[str], int]:
    decl_lines = _format_verbatim_declaration(decl).split("\n")
    end_line = start_line + len(decl_lines) - 1
    provenance = (
        f"-- [EXTRACTED_DEF upstream={decl.upstream_path}:{decl.start_line}-{decl.end_line} "
        f"commit={decl.upstream_commit} body_sha256={decl.body_sha256}]"
    )
    return [*decl_lines, provenance], end_line


def _emit_stub_block(
    decl: LeanDeclaration,
    *,
    start_line: int,
) -> tuple[list[str], int]:
    sig_lines = f"{decl.signature} := by".split("\n")
    sorry_line = (
        f"  sorry -- [EXTRACTED_STUB "
        f"upstream={decl.upstream_path}:{decl.start_line}-{decl.end_line} "
        f"commit={decl.upstream_commit} body_lines={decl.body_lines} "
        f"body_sha256={decl.body_sha256}]"
    )
    block_lines = [*sig_lines, sorry_line]
    end_line = start_line + len(block_lines) - 1
    return block_lines, end_line


def _header_lines(module: ExtractedModule, *, preserve_defs: bool) -> list[str]:
    preserve_flag = "true" if preserve_defs else "false"
    return [
        "-- AUTO-GENERATED by rh-extract. Do not edit by hand.",
        f"-- Upstream: {module.upstream_path} @ {module.upstream_commit}",
        f"-- Preserve defs: {preserve_flag}",
    ]


def render_skeleton_file(
    module: ExtractedModule,
    *,
    preserve_defs: bool = False,
) -> tuple[str, tuple[DagDeclarationRef, ...]]:
    """Render a deterministic Lean skeleton file and line-anchored declaration refs."""
    lines = _header_lines(module, preserve_defs=preserve_defs)
    refs: list[DagDeclarationRef] = []

    for decl in module.declarations:
        lines.append("")
        skel_start_line = len(lines) + 1
        if _should_emit_verbatim(decl.kind, preserve_defs=preserve_defs):
            block_lines, skel_end_line = _emit_verbatim_block(decl, start_line=skel_start_line)
        else:
            block_lines, skel_end_line = _emit_stub_block(decl, start_line=skel_start_line)
        lines.extend(block_lines)
        refs.append(
            DagDeclarationRef(
                name=decl.name,
                kind=decl.kind,
                start_line=skel_start_line,
                end_line=skel_end_line,
                upstream_path=decl.upstream_path,
                upstream_start_line=decl.start_line,
                upstream_end_line=decl.end_line,
            )
        )

    return "\n".join(lines) + "\n", tuple(refs)
