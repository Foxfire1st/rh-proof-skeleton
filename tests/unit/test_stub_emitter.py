def _make_decl(
    *,
    name: str,
    kind: LeanDeclarationKind,
    signature: str,
    body: str,
    start_line: int,
    end_line: int,
    body_sha256: str = "a" * 64,
) -> LeanDeclaration:
    body_lines = 0 if body == "" else len(body.split("\n"))
    return LeanDeclaration(
        name=name,
        kind=kind,
        signature=signature,
        body=body,
        start_line=start_line,
        end_line=end_line,
        upstream_path=_UPSTREAM_PATH,
        upstream_commit=_UPSTREAM_COMMIT,
        body_lines=body_lines,
        body_sha256=body_sha256,
    )


