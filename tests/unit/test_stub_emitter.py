def _expected_verbatim_lines(decl: LeanDeclaration) -> list[str]:
    if decl.body == "":
        text = decl.signature
    elif decl.body.startswith((" ", "\t")):
        text = f"{decl.signature} :=\n{decl.body}"
    else:
        text = f"{decl.signature} := {decl.body}"
    return text.split("\n")


@pytest.mark.parametrize("preserve_defs", [False, True])
def test_empty_module_renders_header_only_and_no_refs(preserve_defs: bool) -> None:
    module = ExtractedModule(
        upstream_path=_UPSTREAM_PATH,
        upstream_commit=_UPSTREAM_COMMIT,
        imports=(),
        declarations=(),
    )

    text, refs = render_skeleton_file(module, preserve_defs=preserve_defs)

    expected_flag = "true" if preserve_defs else "false"
    assert text == (
        "-- AUTO-GENERATED by rh-extract. Do not edit by hand.\n"
        f"-- Upstream: {_UPSTREAM_PATH} @ {_UPSTREAM_COMMIT}\n"
        f"-- Preserve defs: {expected_flag}\n"
    )
    assert refs == ()


@pytest.mark.parametrize("preserve_defs", [False, True])
def test_all_ten_kinds_verbatim_vs_stub_and_exact_line_alignment(preserve_defs: bool) -> None:
    module = _all_ten_kinds_module()
    verbatim_kinds = {"structure", "inductive", "class", "opaque", "axiom"}
    if preserve_defs:
        verbatim_kinds |= {"def", "abbrev"}

    text, refs = render_skeleton_file(module, preserve_defs=preserve_defs)
    assert text.endswith("\n")
    assert not text.endswith("\n\n")

    lines = text.splitlines()
    assert lines[0] == "-- AUTO-GENERATED by rh-extract. Do not edit by hand."
    assert lines[1] == f"-- Upstream: {_UPSTREAM_PATH} @ {_UPSTREAM_COMMIT}"
    assert lines[2] == f"-- Preserve defs: {'true' if preserve_defs else 'false'}"
    assert len(refs) == len(module.declarations)

    for decl, ref in zip(module.declarations, refs, strict=True):
        assert ref.name == decl.name
        assert ref.kind == decl.kind
        assert ref.upstream_path == decl.upstream_path
        assert ref.upstream_start_line == decl.start_line
        assert ref.upstream_end_line == decl.end_line

        # Preceding line is always a single blank separator line.
        assert lines[ref.start_line - 2] == ""
        span = lines[ref.start_line - 1 : ref.end_line]

        if decl.kind in verbatim_kinds:
            assert span == _expected_verbatim_lines(decl)
            assert lines[ref.end_line] == (
                "-- [EXTRACTED_DEF "
                f"upstream={decl.upstream_path}:{decl.start_line}-{decl.end_line} "
                f"commit={decl.upstream_commit} body_sha256={decl.body_sha256}]"
            )
        else:
            expected_sig = f"{decl.signature} := by".split("\n")
            expected_sorry = (
                f"  sorry -- [EXTRACTED_STUB "
                f"upstream={decl.upstream_path}:{decl.start_line}-{decl.end_line} "
                f"commit={decl.upstream_commit} body_lines={decl.body_lines} "
                f"body_sha256={decl.body_sha256}]"
            )
            assert span == [*expected_sig, expected_sorry]


def test_verbatim_def_single_line_and_multiline_indented_bodies() -> None:
    single_line_def = _make_decl(
        name="addOne",
        kind="def",
        signature="def addOne (n : Nat) : Nat",
        body="n + 1",
        start_line=5,
        end_line=5,
        body_sha256="b" * 64,
    )
    space_indented_def = _make_decl(
        name="predNat",
        kind="def",
        signature="def predNat (n : Nat) : Nat",
        body="  match n with\n  | 0 => 0\n  | k + 1 => k",
        start_line=7,
        end_line=10,
        body_sha256="c" * 64,
    )
    tab_indented_abbrev = _make_decl(
        name="tabId",
        kind="abbrev",
        signature="abbrev tabId (n : Nat) : Nat",
        body="\tn",
        start_line=12,
        end_line=13,
        body_sha256="d" * 64,
    )
    module = ExtractedModule(
        upstream_path=_UPSTREAM_PATH,
        upstream_commit=_UPSTREAM_COMMIT,
        imports=(),
        declarations=(single_line_def, space_indented_def, tab_indented_abbrev),
    )

    text, refs = render_skeleton_file(module, preserve_defs=True)
    expected = (
        "-- AUTO-GENERATED by rh-extract. Do not edit by hand.\n"
        f"-- Upstream: {_UPSTREAM_PATH} @ {_UPSTREAM_COMMIT}\n"
        "-- Preserve defs: true\n"
        "\n"
        "def addOne (n : Nat) : Nat := n + 1\n"
        f"-- [EXTRACTED_DEF upstream={_UPSTREAM_PATH}:5-5 "
        f"commit={_UPSTREAM_COMMIT} body_sha256={'b' * 64}]\n"
        "\n"
        "def predNat (n : Nat) : Nat :=\n"
        "  match n with\n"
        "  | 0 => 0\n"
        "  | k + 1 => k\n"
        f"-- [EXTRACTED_DEF upstream={_UPSTREAM_PATH}:7-10 "
        f"commit={_UPSTREAM_COMMIT} body_sha256={'c' * 64}]\n"
        "\n"
        "abbrev tabId (n : Nat) : Nat :=\n"
        "\tn\n"
        f"-- [EXTRACTED_DEF upstream={_UPSTREAM_PATH}:12-13 "
        f"commit={_UPSTREAM_COMMIT} body_sha256={'d' * 64}]\n"
    )
    assert text == expected
    assert refs == (
        DagDeclarationRef(
            name="addOne",
            kind="def",
            start_line=5,
            end_line=5,
            upstream_path=_UPSTREAM_PATH,
            upstream_start_line=5,
            upstream_end_line=5,
        ),
        DagDeclarationRef(
            name="predNat",
            kind="def",
            start_line=8,
            end_line=11,
            upstream_path=_UPSTREAM_PATH,
            upstream_start_line=7,
            upstream_end_line=10,
        ),
        DagDeclarationRef(
            name="tabId",
            kind="abbrev",
            start_line=14,
            end_line=15,
            upstream_path=_UPSTREAM_PATH,
            upstream_start_line=12,
            upstream_end_line=13,
        ),
    )


def test_stubbed_def_and_theorem_exact_rendered_output() -> None:
    decl_def = _make_decl(
        name="predNat",
        kind="def",
        signature="def predNat (n : Nat) : Nat",
        body="  match n with\n  | 0 => 0\n  | k + 1 => k",
        start_line=7,
        end_line=10,
        body_sha256="c" * 64,
    )
    decl_thm = _make_decl(
        name="pred_zero",
        kind="theorem",
        signature="theorem pred_zero :\n    predNat 0 = 0",
        body="  rfl",
        start_line=12,
        end_line=14,
        body_sha256="e" * 64,
    )
    module = ExtractedModule(
        upstream_path=_UPSTREAM_PATH,
        upstream_commit=_UPSTREAM_COMMIT,
        imports=(),
        declarations=(decl_def, decl_thm),
    )

    text, refs = render_skeleton_file(module, preserve_defs=False)
    expected = (
        "-- AUTO-GENERATED by rh-extract. Do not edit by hand.\n"
        f"-- Upstream: {_UPSTREAM_PATH} @ {_UPSTREAM_COMMIT}\n"
        "-- Preserve defs: false\n"
        "\n"
        "def predNat (n : Nat) : Nat := by\n"
        f"  sorry -- [EXTRACTED_STUB upstream={_UPSTREAM_PATH}:7-10 "
        f"commit={_UPSTREAM_COMMIT} body_lines=3 body_sha256={'c' * 64}]\n"
        "\n"
        "theorem pred_zero :\n"
        "    predNat 0 = 0 := by\n"
        f"  sorry -- [EXTRACTED_STUB upstream={_UPSTREAM_PATH}:12-14 "
        f"commit={_UPSTREAM_COMMIT} body_lines=1 body_sha256={'e' * 64}]\n"
    )
    assert text == expected
    assert refs == (
        DagDeclarationRef(
            name="predNat",
            kind="def",
            start_line=5,
            end_line=6,
            upstream_path=_UPSTREAM_PATH,
            upstream_start_line=7,
            upstream_end_line=10,
        ),
        DagDeclarationRef(
            name="pred_zero",
            kind="theorem",
            start_line=8,
            end_line=10,
            upstream_path=_UPSTREAM_PATH,
            upstream_start_line=12,
            upstream_end_line=14,
        ),
    )


def test_deterministic_byte_identical_rerendering() -> None:
    module = _all_ten_kinds_module()
    for preserve_defs in (False, True):
        first_text, first_refs = render_skeleton_file(module, preserve_defs=preserve_defs)
        second_text, second_refs = render_skeleton_file(module, preserve_defs=preserve_defs)
        assert first_text.encode("utf-8") == second_text.encode("utf-8")
        assert first_refs == second_refs
